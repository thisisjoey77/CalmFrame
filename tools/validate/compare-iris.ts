/**
 * compare-iris (docs/SPEC.md, Prompt 8, step 3): read IRIS's per-frame CSV and CalmFrame's
 * per-second CSVs for each clip in the manifest, reduce both to pass or fail per second,
 * and write a two-by-two agreement table, per clip and in total, with the seconds that
 * disagree, for both CalmFrame setups. Saved under measurements/.
 *
 *   node tools/validate/dist/tools/validate/compare-iris.js <clipDir> <calmframeDir> <irisDir> [outPrefix]
 *
 * irisDir holds IRIS's output folders, one per clip: <irisDir>/<clip>.mp4/framedata.csv.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { csvToRows, secondFails, type SecondRow } from './analyse'
import {
  addTables,
  agreement,
  calmFrameWord,
  clipVerdict,
  compareSeconds,
  emptyTable,
  irisClipFails,
  percent,
  secondRanges,
  tableTotal,
  type SecondComparison,
  type Table
} from './compare'
import { irisSecondFails, irisSeconds, parseIrisCsv, type IrisSecond } from './iris'
import type { Manifest } from './make-clips'

const MODES = [
  {
    name: 'iris',
    label: 'IRIS-compatible area (whole frame), strict trigger, extended-failure rule'
  },
  { name: 'wcag', label: 'WCAG area (a 10° window), strict trigger' }
] as const

export interface ClipResult {
  id: string
  title: string
  expected: Manifest['clips'][number]['expected']
  iris: IrisSecond[]
  ours: Record<string, SecondRow[]>
  comparisons: Record<string, SecondComparison>
}

export function loadClipResult(
  clip: Manifest['clips'][number],
  calmFrameDir: string,
  irisDir: string
): ClipResult {
  const iris = irisSeconds(
    parseIrisCsv(readFileSync(join(irisDir, clip.file, 'framedata.csv'), 'utf8'))
  )
  const ours: Record<string, SecondRow[]> = {}
  const comparisons: Record<string, SecondComparison> = {}
  for (const m of MODES) {
    ours[m.name] = csvToRows(readFileSync(join(calmFrameDir, `${clip.id}.${m.name}.csv`), 'utf8'))
    comparisons[m.name] = compareSeconds(ours[m.name], iris)
  }
  return { id: clip.id, title: clip.title, expected: clip.expected, iris, ours, comparisons }
}

const verdictWord = (v: ReturnType<typeof clipVerdict>): string =>
  v === 'safe'
    ? 'safe'
    : v === 'red'
      ? 'red hazard'
      : v === 'luminance'
        ? 'hazard'
        : 'extended fail'

const expectedWcag = (e: ClipResult['expected']): string =>
  e.wcag === 'safe' ? 'safe' : e.wcag === 'red' ? 'red hazard' : 'hazard'

/** Does CalmFrame's clip verdict in WCAG mode match the spec's expectation? */
function wcagMatches(r: ClipResult): boolean {
  const v = clipVerdict(r.ours['wcag'])
  return r.expected.wcag === 'safe' ? v === 'safe' : v === r.expected.wcag
}

function irisModeMatches(r: ClipResult): boolean {
  return r.ours['iris'].some(secondFails) === (r.expected.iris === 'fail')
}

const tableRow = (label: string, t: Table): string =>
  `| ${label} | ${t.bothFail} | ${t.bothPass} | ${t.onlyIris} | ${t.onlyCalmFrame} | ${percent(agreement(t))} |`

export interface ReportMeta {
  irisVersion: string
  generatedAt: string
}

export function reportMarkdown(results: readonly ClipResult[], meta: ReportMeta): string {
  const totals: Record<string, Table> = {}
  for (const m of MODES) {
    totals[m.name] = results.reduce(
      (t, r) => addTables(t, r.comparisons[m.name].table),
      emptyTable()
    )
  }
  const seconds = tableTotal(totals['iris'])
  const lines: string[] = []
  lines.push('# CalmFrame compared against IRIS (Python port)', '')
  lines.push(
    `Generated by \`npm run validate:all\` on ${meta.generatedAt}. ${results.length} synthetic clips from the spec's "Test clips" table (10 s, 1920×1080, 60 fps, 3 s steady lead-in), ${seconds} seconds in all. IRIS is the community Python port, \`iris-pse-detection\` ${meta.irisVersion}, with its default settings. CalmFrame is \`tools/validate\` running the detector in \`src/core\`, the same code as the app.`,
    ''
  )
  lines.push(
    'A second fails if any frame in it fails. For IRIS that is a luminance or red result of extended failure or failure. For CalmFrame it is a hazard, or the extended-failure rule where that setup has it. Warnings count as passes.',
    ''
  )
  lines.push('## Per-second agreement', '')
  lines.push(
    '| CalmFrame setup | Both fail | Both pass | Only IRIS fails | Only CalmFrame fails | Agreement |'
  )
  lines.push('| --- | --- | --- | --- | --- | --- |')
  for (const m of MODES) lines.push(tableRow(m.label, totals[m.name]))
  lines.push('')
  lines.push('## Per clip', '')
  lines.push(
    '| Clip | Spec expects (WCAG / IRIS) | IRIS | CalmFrame, IRIS setup | CalmFrame, WCAG setup | Agreement, IRIS setup | Agreement, WCAG setup |'
  )
  lines.push('| --- | --- | --- | --- | --- | --- | --- |')
  for (const r of results) {
    const irisV = irisClipFails(r.iris) ? 'fail' : 'pass'
    const ourIris = r.ours['iris'].some(secondFails)
      ? verdictWord(clipVerdict(r.ours['iris']))
      : 'pass'
    const ourWcag = verdictWord(clipVerdict(r.ours['wcag']))
    const mark = (ok: boolean): string => (ok ? '' : ' ✗')
    lines.push(
      `| ${r.title} | ${expectedWcag(r.expected)} / ${r.expected.irisNote.toLowerCase()} | ${irisV}${mark(irisV === r.expected.iris)} | ${ourIris}${mark(irisModeMatches(r))} | ${ourWcag}${mark(wcagMatches(r))} | ${percent(agreement(r.comparisons['iris'].table))} | ${percent(agreement(r.comparisons['wcag'].table))} |`
    )
  }
  lines.push('', '✗ marks a clip verdict that differs from what the spec expects.', '')
  lines.push('## Seconds that disagree', '')
  let any = false
  for (const m of MODES) {
    for (const r of results) {
      const d = r.comparisons[m.name].disagreements
      if (d.length === 0) continue
      any = true
      const detail = d
        .map((x) => `${x.second}: CalmFrame ${x.calmFrame}, IRIS ${x.iris}`)
        .join('; ')
      lines.push(
        `- **${r.title}**, ${m.name.toUpperCase()} setup, seconds ${secondRanges(d.map((x) => x.second))}. ${detail}.`
      )
    }
  }
  if (!any) lines.push('None.')
  lines.push('')
  return `${lines.join('\n')}\n`
}

/** One row per clip, setup and second, for anyone who wants the raw comparison. */
export function reportCsv(results: readonly ClipResult[]): string {
  const rows = [
    'clip,second,iris_luminance,iris_red,iris_fails,calmframe_setup,calmframe_graph_max,calmframe_verdict,calmframe_fails'
  ]
  for (const r of results) {
    for (const m of MODES) {
      const ours = r.ours[m.name]
      for (let s = 0; s < Math.min(ours.length, r.iris.length); s++) {
        const i = r.iris[s]
        rows.push(
          [
            r.id,
            s,
            i.luminance,
            i.red,
            irisSecondFails(i) ? 'yes' : 'no',
            m.name,
            ours[s].graphMax.toFixed(1),
            calmFrameWord(ours[s]),
            secondFails(ours[s]) ? 'yes' : 'no'
          ].join(',')
        )
      }
    }
  }
  return `${rows.join('\n')}\n`
}

export function compareAll(
  clipDir: string,
  calmFrameDir: string,
  irisDir: string,
  outPrefix: string,
  meta: ReportMeta
): ClipResult[] {
  const manifest = JSON.parse(readFileSync(join(clipDir, 'manifest.json'), 'utf8')) as Manifest
  const results = manifest.clips.map((c) => loadClipResult(c, calmFrameDir, irisDir))
  writeFileSync(`${outPrefix}.md`, reportMarkdown(results, meta))
  writeFileSync(`${outPrefix}.csv`, reportCsv(results))
  return results
}

if (require.main === module) {
  const [clipDir, ourDir, irisDir, prefix] = process.argv.slice(2)
  if (!clipDir || !ourDir || !irisDir) {
    console.error('usage: compare-iris <clipDir> <calmframeDir> <irisDir> [outPrefix]')
    process.exit(1)
  }
  const out = resolve(prefix ?? 'measurements/iris-comparison')
  compareAll(resolve(clipDir), resolve(ourDir), resolve(irisDir), out, {
    irisVersion: process.env['CALMFRAME_IRIS_VERSION'] ?? 'unknown',
    generatedAt: new Date().toISOString()
  })
  console.log(`[compare-iris] wrote ${out}.md and ${out}.csv`)
}
